"""Build a human- and machine-readable map of every simulation dataset on disk.

Read-only over raw data: walks campaign trees, reads spec.json / COMPLETE /
summary.json, and writes an index next to them. Never modifies or deletes a run.
"""
import dataclasses, json, os, sys
from pathlib import Path

ROOT = Path('/home/sk57289/io_equilibrium_sim')
CAMP = ROOT / 'results/workflow_campaign'
sys.path.insert(0, str(ROOT))
from config import SimConfig

DEFAULTS = {f.name: (getattr(SimConfig(), f.name) if not dataclasses.is_dataclass(getattr(SimConfig(), f.name)) else None)
            for f in dataclasses.fields(SimConfig())}
SKIP = {'duration_s', 'seed', 'pkj', 'dcn', 'io_channels'}

# What each campaign was for, in one line. Keyed by directory name.
PURPOSE = {
    'background_20260918T160421Z':
        'First long campaign. 5 simulated hours x 9 conditions, seed 0: baseline, gap coupling '
        'off/half/strong, IO heterogeneity 0.15/0.30, PF strength half/double, and one combined. '
        'Superseded for the plasticity-rule question but still the reference for gap/heterogeneity.',
    'homeostasis_20260921T034911Z':
        'Homeostatic synaptic scaling replacing the heterogeneity/fixed-gain perturbation. '
        '4 simulated hours; tests whether multiplicative rate-targeting rescues individual-synapse stability.',
    'cascade_20260921T145424Z':
        'Abbott and Mauk cascade plasticity implemented and compared against additive and binary. '
        'Short (120 s) validation + assay runs; the pre-optimization reference the native build was checked against.',
    'realtime_20260921T160422Z':
        'Post-optimization production campaign: 4 simulated hours x 4 plasticity rules x seeds 0,1. '
        'The current best plasticity-rule comparison. All 8 runs COMPLETE and analyzed.',
}

def deltas(cfg):
    out = {}
    for k, v in cfg.items():
        if k in SKIP or k not in DEFAULTS:
            continue
        if DEFAULTS[k] is not None and DEFAULTS[k] != v:
            out[k] = v
    return out

def scan():
    campaigns = []
    for cdir in sorted(CAMP.iterdir()):
        if not cdir.is_dir():
            continue
        runs = []
        for rdir in sorted((cdir / 'runs').glob('*')) if (cdir / 'runs').is_dir() else []:
            spec_p = rdir / 'spec.json'
            if not spec_p.exists():
                continue
            spec = json.loads(spec_p.read_text())
            cfg = spec['config']
            complete = (rdir / 'COMPLETE').exists()
            adir = cdir / 'analysis' / rdir.name
            summary = None
            sp = adir / 'summary.json'
            if sp.exists():
                try:
                    summary = json.loads(sp.read_text())
                except Exception:
                    summary = None
            m = (summary or {}).get('measured', {})
            runs.append(dict(
                id=rdir.name, condition=spec.get('condition'), seed=cfg.get('seed'),
                simulated_hours=round(cfg['duration_s'] / 3600, 2),
                plasticity_mode=cfg.get('plasticity_mode', 'additive'),
                non_default_config=deltas(cfg), complete=complete,
                raw_dir=str(rdir), raw_bytes=sum(p.stat().st_size for p in rdir.rglob('*') if p.is_file()),
                analysis_dir=str(adir) if adir.exists() else None,
                cf_rate_hz=m.get('population_rate_hz', {}).get('io'),
                pkj_rate_hz=m.get('population_rate_hz', {}).get('pkj'),
                final_mean_weight=m.get('final_mean_weight'),
                final_within_pkj_sd=m.get('final_within_pkj_rms_sd'),
                mean_weight_slope_per_hour=m.get('mean_weight_slope_last_20_percent_per_hour'),
            ))
        campaigns.append(dict(
            name=cdir.name, purpose=PURPOSE.get(cdir.name, 'Purpose not recorded.'),
            path=str(cdir), total_bytes=sum(p.stat().st_size for p in cdir.rglob('*') if p.is_file()),
            n_runs=len(runs), n_complete=sum(r['complete'] for r in runs),
            campaign_complete=(cdir / 'control' / 'CAMPAIGN_COMPLETE.json').exists()
                              or (cdir / 'CAMPAIGN_COMPLETE.json').exists(),
            runs=runs))
    return campaigns

def md(campaigns):
    L = ['# Simulation data index', '',
         'Auto-generated by `experiments/build_index.py`. Every dataset on this machine,',
         'what question it answers, and whether it finished. Raw run directories are immutable;',
         'analysis lives in a sibling `analysis/` directory, never inside the raw bundle.', '',
         '## Campaigns', '']
    L += ['| campaign | what it is for | runs | complete | size |', '|---|---|---|---|---|']
    for c in campaigns:
        L.append(f"| `{c['name']}` | {c['purpose'].split('.')[0]}. | {c['n_runs']} | "
                 f"{c['n_complete']}/{c['n_runs']} | {c['total_bytes']/2**30:.2f} GB |")
    L.append('')
    for c in campaigns:
        L += [f"## `{c['name']}`", '', c['purpose'], '',
              f"Path: `{c['path']}`  ", f"Size: {c['total_bytes']/2**30:.2f} GB  ",
              f"Runs: {c['n_complete']}/{c['n_runs']} complete", '']
        if not c['runs']:
            L += ['_No runs under `runs/` (validation- or pilot-only campaign)._', '']
            continue
        L += ['| run | sim hours | non-default settings | done | CF Hz | PKJ Hz | mean w | within-cell SD |',
              '|---|---|---|---|---|---|---|---|']
        for r in c['runs']:
            knobs = ', '.join(f'`{k}`={v}' for k, v in r['non_default_config'].items()) or '_shipped defaults_'
            def f(x, n=3):
                return f'{x:.{n}f}' if isinstance(x, (int, float)) else '—'
            L.append(f"| `{r['id']}` | {r['simulated_hours']} | {knobs} | {'yes' if r['complete'] else 'NO'} | "
                     f"{f(r['cf_rate_hz'])} | {f(r['pkj_rate_hz'],2)} | {f(r['final_mean_weight'])} | {f(r['final_within_pkj_sd'])} |")
        L.append('')
    return '\n'.join(L) + '\n'

if __name__ == '__main__':
    cs = scan()
    dest = Path(sys.argv[1]) if len(sys.argv) > 1 else CAMP.parent
    (dest / 'index.json').write_text(json.dumps(cs, indent=2) + '\n')
    (dest / 'INDEX.md').write_text(md(cs))
    print(f"wrote {dest/'INDEX.md'} and {dest/'index.json'}")
    for c in cs:
        print(f"  {c['name']:<34} {c['n_complete']}/{c['n_runs']} complete  {c['total_bytes']/2**30:5.2f} GB")
